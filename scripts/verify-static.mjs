import { readFile, access, readdir } from 'node:fs/promises'
import path from 'node:path'
const dir = path.resolve('.output/public')
const manifest = JSON.parse(await readFile('shared/content-manifest.json', 'utf8'))
const base = ('/' + (process.env.NUXT_APP_BASE_URL || '/').replace(/^\/+|\/+$/g, '') + '/').replace(/\/+/g, '/')
const origin = (process.env.SITE_URL || 'https://amkargar.github.io').replace(/\/$/, '')
const errors = []; let links = 0; const titles = new Set(); const descriptions = new Set()
const pages = [{path:'/'},{path:'/blog/'},...manifest]
for (const p of pages) {
 const file = path.join(dir,p.path,'index.html'); let html
 try { html = await readFile(file,'utf8') } catch { errors.push(`Missing page: ${p.path}`);continue }
 const title = html.match(/<title>(.*?)<\/title>/s)?.[1]
 if (!title || titles.has(title)) errors.push(`Missing/duplicate title: ${p.path}`);titles.add(title)
 const desc = html.match(/<meta name="description" content="([^"]+)"/)?.[1]
 if (!desc || descriptions.has(desc)) errors.push(`Missing/duplicate description: ${p.path}`);descriptions.add(desc)
 if ((html.match(/<h1(?:\s|>)/g)||[]).length !== 1) errors.push(`Expected exactly one H1: ${p.path}`)
 if (p.type && !html.includes(p.title.replace(/&/g,'&amp;'))) errors.push(`Content missing from static HTML: ${p.path}`)
 const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1]
 if (canonical !== origin+base+p.path.replace(/^\//,'')) errors.push(`Incorrect canonical: ${p.path}: ${canonical}`)
 if (!html.includes('property="og:image"') || !html.includes('name="twitter:card"')) errors.push(`Missing social metadata: ${p.path}`)
 const expectedRobots = process.env.PUBLIC_INDEXING === 'true' ? 'index, follow' : 'noindex, nofollow'
 if (!html.includes(expectedRobots)) errors.push(`Wrong indexing policy: ${p.path}`)
 for (const m of html.matchAll(/<script[^>]+type="application\/ld\+json"[^>]*>(.*?)<\/script>/gs)) { try { JSON.parse(m[1]) } catch { errors.push(`Invalid JSON-LD: ${p.path}`) } }
 for (const m of html.matchAll(/(?:href|src)="([^"]+)"/g)) {
  let href = m[1].split(/[?#]/)[0]
  if (!href.startsWith('/') || href.startsWith('//')) continue
  if (!href.startsWith(base)) { errors.push(`Root-only link with base ${base}: ${p.path}: ${href}`);continue }
  href=href.slice(base.length)
  if (!href || href.endsWith('/')) href += 'index.html'
  else if (!path.extname(href)) href += '/index.html'
  try { await access(path.join(dir,decodeURI(href)));links++ } catch { errors.push(`Missing link/asset: ${p.path}: ${href}`) }
 }
}
for (const file of ['sitemap.xml','robots.txt','feed.xml','site.webmanifest','.nojekyll','favicon.ico','apple-touch-icon.png','icon-192.png','icon-512.png','og/gonex.png','404.html']) { try { await access(path.join(dir,file)) } catch { errors.push(`Missing SEO file: ${file}`) } }
const sitemap=await readFile(path.join(dir,'sitemap.xml'),'utf8')
for (const p of pages) if (!sitemap.includes(origin+base+p.path.replace(/^\//,''))) errors.push(`Missing sitemap URL: ${p.path}`)
const webmanifest=JSON.parse(await readFile(path.join(dir,'site.webmanifest'),'utf8'))
if(webmanifest.scope !== base || webmanifest.start_url !== base) errors.push('Incorrect manifest base')
const moved = await readFile(path.join(dir, 'docs', 'main', 'building-websites', 'index.html'), 'utf8')
if (!moved.includes(`content="0;url=${base}docs/main/building-api/"`) || !moved.includes('noindex, follow')) errors.push('Missing base-aware legacy tutorial redirect')
const notFound=await readFile(path.join(dir,'404.html'),'utf8')
if(!notFound.includes('noindex')) errors.push('404 should be noindex')
// CSS is generated by Vite; catch font URLs that bypass a GitHub project base.
async function checkCss(folder) {for(const d of await readdir(folder,{withFileTypes:true})) {const f=path.join(folder,d.name);if(d.isDirectory()) await checkCss(f);else if(d.name.endsWith('.css')) {const css=await readFile(f,'utf8');for(const m of css.matchAll(/url\(["']?(\/fonts\/[^)"']+)/g)) if(base!=='/') errors.push(`CSS font URL bypasses base: ${m[1]}`)}}}
await checkCss(path.join(dir,'_nuxt'))
if(errors.length){console.error([...new Set(errors)].join('\n'));process.exit(1)}
console.log(`PASS: ${pages.length} prerendered pages; ${links} local links/assets; unique SEO, canonical, schema, indexing, sitemap, icons and ${base} base path.`)
